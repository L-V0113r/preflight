"""Write evaluation results as a readable Markdown report (plus raw JSON)."""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

NICE_NAMES = {
    "keyword_baseline": "Keyword baseline",
    "rules_only": "Rules only",
    "model_only": "Model only",
    "preflight_hybrid": "**PreFlight (rules + model)**",
}


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def _system_rows(lines: list[str], systems: dict) -> None:
    for key, metrics in systems.items():
        lines.append(
            f"| {NICE_NAMES[key]} | {_pct(metrics['recall'])} | {_pct(metrics['false_positive_rate'])} | "
            f"{_pct(metrics['precision'])} | {metrics['f1']:.3f} | {metrics['tp']} | {metrics['fp']} | "
            f"{metrics['tn']} | {metrics['fn']} |")


def write_report(report: dict, out_dir: Path) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    report = {"generated_at": stamp, **report}
    (out_dir / "evaluation_report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")

    d = report["data"]
    lines = [
        "# PreFlight evaluation report",
        "",
        f"Generated {stamp} by `python evaluate.py`.",
        "",
        "> **Read this first.** Every number below comes from **labelled synthetic pages**",
        "> generated by `preflight/data/synthetic.py`, not from real browsing. Synthetic",
        "> results show that the pipeline works and how the parts compare; they do **not**",
        "> prove real-world accuracy. See `readme/ai_techniques/04_evaluation.md`.",
        "",
        "## Data",
        "",
        f"- Seed {d['seed']}; {d['n_total']} pages in total.",
        f"- Training split: {d['n_train']} pages. Held-out test split: {d['n_test']} pages "
        f"({d['n_test_malicious']} malicious, {d['n_test_benign']} benign, "
        f"{d['n_test_url_only']} with content withheld to mimic failed fetches).",
        f"- Model chosen by 5-fold cross-validation: `{report['training']['chosen_algorithm']}`.",
        "",
        "## Headline comparison (held-out test split)",
        "",
        "| System | Detection rate (recall) | False alarms (FPR) | Precision | F1 | TP | FP | TN | FN |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    _system_rows(lines, report["systems"])
    lines += [
        "",
        "Here *flagged* means a Caution or Danger warning. PreFlight's **Unsure** answers count as",
        "not flagged in this table, even though they also stop the page and ask the user (see below).",
        "",
        "### Only pages whose content could be read",
        "",
        "| System | Detection rate (recall) | False alarms (FPR) | Precision | F1 | TP | FP | TN | FN |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    _system_rows(lines, report["systems_content_readable"])
    ux = report["user_experience"]
    lines += [
        "",
        "## What the user experiences (PreFlight)",
        "",
        "The number that matters most for protection is how often a malicious page opens",
        "**silently**. Unsure pages are not opened silently: the user sees why and decides.",
        "",
        "| Pages | n | Opened silently | Asked (Unsure) | Warned (Caution/Danger) |",
        "|---|---|---|---|---|",
    ]
    for key, label in (("malicious", "Malicious, all"), ("malicious_content_readable", "Malicious, content readable"),
                       ("benign", "Benign, all"), ("benign_content_readable", "Benign, content readable")):
        row = ux[key]
        lines.append(f"| {label} | {row['n']} | {_pct(row['opened_silently'])} | "
                     f"{_pct(row['asked_unsure'])} | {_pct(row['warned'])} |")
    mq, unc = report["model_quality"], report["uncertainty"]
    lines += [
        "",
        f"Model ROC-AUC {mq['roc_auc']}, Brier score {mq['brier_score']} (lower is better calibrated).",
        "",
        "## Honest uncertainty (the trade-off)",
        "",
        "PreFlight answers **Unsure** instead of **Safe** when it could not read the page, the model",
        "is undecided, or the page is unlike its training data. Unsure pages are shown to the user",
        "with an explanation rather than silently loaded. This costs some interruptions:",
        "",
        f"- Benign pages answered Unsure: {_pct(unc['unsure_rate_benign'])} overall, "
        f"{_pct(unc['unsure_rate_benign_with_content'])} of those whose content could be read",
        f"- Malicious pages answered Unsure (not flagged, but not called safe either): "
        f"{_pct(unc['unsure_rate_malicious'])}",
        f"- Pages whose content could not be read, answered Unsure: {_pct(unc['unsure_rate_url_only_pages'])}",
        "",
        "## Per family (PreFlight hybrid)",
        "",
        "For malicious families *flagged* = caught. For benign families *flagged* = false alarm.",
        "",
        "| Family | Malicious? | n | Flagged | Unsure | Keyword baseline flagged |",
        "|---|---|---|---|---|---|",
    ]
    for family, row in report["per_family"].items():
        lines.append(f"| {family} | {'yes' if row['malicious'] else 'no'} | {row['n']} | "
                     f"{_pct(row['flagged_rate'])} | {_pct(row['unsure_rate'])} | "
                     f"{_pct(row['keyword_flagged_rate'])} |")

    if "leave_one_family_out" in report:
        lines += [
            "",
            "## Unseen attack types (leave-one-family-out)",
            "",
            "The model is retrained **without** one attack family, then tested on that family.",
            "This shows how much the model generalises and how much the rules carry.",
            "",
            "| Held-out family | n | Model only (unseen) | Rules only | PreFlight hybrid (model unseen) |",
            "|---|---|---|---|---|",
        ]
        for family, row in report["leave_one_family_out"].items():
            lines.append(f"| {family} | {row['n']} | {_pct(row['model_only_recall_unseen'])} | "
                         f"{_pct(row['rules_only_recall'])} | {_pct(row['hybrid_recall_unseen'])} |")

    lat = report["latency_ms_offline"]
    lines += [
        "",
        "## Speed",
        "",
        f"Offline analysis per page: median {lat['median']} ms, 95th percentile {lat['p95']} ms. "
        f"({lat['note']}.)",
        "",
    ]
    path = out_dir / "evaluation_report.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path
